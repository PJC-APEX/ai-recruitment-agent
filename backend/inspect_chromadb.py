"""
Script to inspect ChromaDB data structure
Run: python inspect_chromadb.py
"""
import asyncio
import json
from app.config import get_settings
from app.services.vector_store_service import VectorStoreService
from app.services.embedding_service import EmbeddingService


async def inspect_chromadb():
    """Inspect the data stored in ChromaDB."""
    
    print("=" * 80)
    print("CHROMADB DATA INSPECTION")
    print("=" * 80)
    
    # Initialize services
    settings = get_settings()
    embedding_service = EmbeddingService(
        api_key=settings.azure_openai_api_key,
        endpoint=settings.azure_openai_endpoint,
        model=settings.azure_openai_embedding_model,
        api_version=settings.azure_openai_api_version
    )
    
    vector_store = VectorStoreService(
        persist_directory=settings.chroma_persist_directory,
        embedding_service=embedding_service
    )
    
    # Get collection info
    print(f"\n📊 Collection Name: {vector_store.collection_name}")
    print(f"📊 Total Documents: {vector_store.get_collection_count()}")
    
    # Get all documents
    results = vector_store.collection.get(
        limit=5,  # Get first 5 documents
        include=["documents", "metadatas", "embeddings"]
    )
    
    if not results["ids"]:
        print("\n⚠️  No documents found in ChromaDB")
        print("\nTo add documents:")
        print("1. Upload a resume PDF via the API: POST /api/upload-resume")
        print("2. Or use the frontend upload feature")
        return
    
    print(f"\n📄 Showing first {len(results['ids'])} documents:\n")
    
    for i, doc_id in enumerate(results["ids"]):
        print(f"\n{'─' * 80}")
        print(f"Document #{i+1}")
        print(f"{'─' * 80}")
        
        # Document ID
        print(f"\n🔑 ID: {doc_id}")
        
        # Metadata
        print(f"\n📋 Metadata:")
        metadata = results["metadatas"][i]
        for key, value in metadata.items():
            if key == "skills" and isinstance(value, list) and len(value) > 5:
                print(f"   {key}: {value[:5]} ... ({len(value)} total)")
            else:
                print(f"   {key}: {value}")
        
        # Document text (truncated)
        doc_text = results["documents"][i]
        print(f"\n📝 Document Text (first 200 chars):")
        print(f"   {doc_text[:200]}...")
        
        # Embedding info
        embedding = results["embeddings"][i]
        print(f"\n🧮 Embedding Vector:")
        print(f"   Dimensions: {len(embedding)}")
        print(f"   First 5 values: {embedding[:5]}")
        print(f"   Last 5 values: {embedding[-5:]}")
    
    print(f"\n{'=' * 80}")
    print("DATA STRUCTURE SUMMARY")
    print(f"{'=' * 80}")
    
    print("""
ChromaDB stores each document with 4 components:

1. 🔑 ID (string): Unique identifier for the document chunk
   Format: {filename}_{uuid}_{chunk_index}
   Example: john_doe_resume.pdf_a3b4c5d6_0

2. 📝 Document (string): The actual text content of the chunk
   - Original resume text split into manageable chunks
   - Used for displaying results to users

3. 📋 Metadata (dict): Associated information about the document
   - file_name: Original PDF filename
   - candidate_name: Extracted candidate name
   - chunk_index: Position in the document (0, 1, 2...)
   - total_chunks: Total number of chunks for this resume
   - skills: List of technical skills (if extracted by LLM)
   - years_experience: Years of experience (if extracted by LLM)

4. 🧮 Embedding (vector): Numerical representation of the text
   - 1536-dimensional vector (for OpenAI text-embedding-3-small)
   - Each dimension is a float between -1 and 1
   - Used for semantic similarity search
   - Generated by Azure OpenAI Embedding model
   - Allows finding similar documents without exact keyword matching
""")
    
    print("\n💡 How it works:")
    print("   • When you upload a resume → it's split into chunks")
    print("   • Each chunk → converted to embedding vector (1536 numbers)")
    print("   • When you search → query is also converted to embedding")
    print("   • ChromaDB finds chunks with closest embedding vectors")
    print("   • This enables semantic search (meaning-based, not keyword-based)")
    
    # Show unique resumes
    all_metadata = vector_store.get_all_metadata()
    unique_files = set()
    skills_example = None
    years_exp_example = None
    
    for meta in all_metadata:
        unique_files.add(meta.get("file_name"))
        if not skills_example and meta.get("skills"):
            skills_example = meta.get("skills")
        if not years_exp_example and meta.get("years_experience"):
            years_exp_example = meta.get("years_experience")
    
    print(f"\n📊 Statistics:")
    print(f"   • Total Chunks: {len(all_metadata)}")
    print(f"   • Unique Resumes: {len(unique_files)}")
    print(f"   • Resume Files: {', '.join(list(unique_files)[:3])}")
    
    if skills_example:
        print(f"\n🎯 Example Extracted Skills:")
        print(f"   {skills_example[:10]}")
    
    if years_exp_example:
        print(f"\n📅 Example Years of Experience: {years_exp_example} years")
    
    print(f"\n{'=' * 80}\n")


if __name__ == "__main__":
    asyncio.run(inspect_chromadb())
